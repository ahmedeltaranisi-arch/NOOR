export function getGovernorateById(govId: string): Governorate | undefined {
  return EGYPT_GOVERNORATES.find((g) => g.id === govId);
}

export function getCityByIds(govId: string, cityId: string): { governorate: Governorate; city: CityLocation } | undefined {
  const governorate = getGovernorateById(govId);
  if (!governorate) return undefined;
  const city = governorate.cities.find((c) => c.id === cityId) || governorate.cities[0];
  return { governorate, city };
}

/**
 * Finds the closest Egyptian governorate & city to arbitrary GPS coordinates
 * using Haversine distance.
 */
export function findNearestEgyptianCity(latitude: number, longitude: number): UserLocation {
  let minDistance = Infinity;
  let nearestGov = EGYPT_GOVERNORATES[0];
  let nearestCity = nearestGov.cities[0];

  const toRad = (deg: number) => (deg * Math.PI) / 180;

  for (const gov of EGYPT_GOVERNORATES) {
    for (const city of gov.cities) {
      const dLat = toRad(city.latitude - latitude);
      const dLon = toRad(city.longitude - longitude);
      const a =
        Math.sin(dLat / 2) * Math.sin(dLat / 2) +
        Math.cos(toRad(latitude)) *
          Math.cos(toRad(city.latitude)) *
          Math.sin(dLon / 2) *
          Math.sin(dLon / 2);
      const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
      const distance = 6371 * c;
      if (distance < minDistance) {
        minDistance = distance;
        nearestGov = gov;
        nearestCity = city;
      }
    }
  }

  return {
    governorateId: nearestGov.id,
    cityId: nearestCity.id,
    governorateNameAr: nearestGov.nameAr,
    cityNameAr: nearestCity.nameAr,
    latitude,
    longitude,
    isCustomGps: true,
    updatedAt: new Date().toISOString(),
  };
}
