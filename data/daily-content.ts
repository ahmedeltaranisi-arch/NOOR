export function getDailyInspiration(date: Date = new Date()): DailyInspirationContent {
  const dayOfYear = Math.floor(
    (date.getTime() - new Date(date.getFullYear(), 0, 0).getTime()) / (1000 * 60 * 60 * 24)
  );
  return {
    ayah: DAILY_AYAT[dayOfYear % DAILY_AYAT.length],
    hadith: DAILY_AHADITH[dayOfYear % DAILY_AHADITH.length],
    dhikr: DAILY_ADHKAR_SNIPPETS[dayOfYear % DAILY_ADHKAR_SNIPPETS.length],
    dua: DAILY_DUAS_SNIPPETS[dayOfYear % DAILY_DUAS_SNIPPETS.length],
  };
}

